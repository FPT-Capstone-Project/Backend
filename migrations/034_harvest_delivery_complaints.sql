BEGIN;

CREATE TABLE IF NOT EXISTS public.complaints (
  complaint_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id INTEGER NOT NULL UNIQUE REFERENCES public.shipments(shipment_id),
  customer_id INTEGER NOT NULL REFERENCES public.users(user_id),
  complaint_type VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  image_urls JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(image_urls) = 'array'),
  status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
  assigned_to INTEGER REFERENCES public.users(user_id),
  resolution TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.complaint_replies (
  reply_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id INTEGER NOT NULL REFERENCES public.complaints(complaint_id) ON DELETE CASCADE,
  sender_id INTEGER NOT NULL REFERENCES public.users(user_id),
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Existing Supabase tables use the earlier seven-status vocabulary.
DO $$
DECLARE c RECORD;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid = 'public.complaints'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) LIKE '%status%'
  LOOP
    EXECUTE format('ALTER TABLE public.complaints DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

UPDATE public.complaints SET status = CASE status
  WHEN 'PENDING' THEN 'OPEN'
  WHEN 'UNDER_REVIEW' THEN 'IN_PROGRESS'
  WHEN 'RESOLVING' THEN 'IN_PROGRESS'
  WHEN 'NEED_MORE_INFO' THEN 'WAITING_CUSTOMER'
  WHEN 'CLOSED' THEN 'RESOLVED'
  ELSE status END;

ALTER TABLE public.complaints ALTER COLUMN status SET DEFAULT 'OPEN';
ALTER TABLE public.complaints ADD CONSTRAINT complaints_status_check
  CHECK (status IN ('OPEN', 'IN_PROGRESS', 'WAITING_CUSTOMER', 'RESOLVED', 'REJECTED'));

CREATE INDEX IF NOT EXISTS complaints_customer_created_idx ON public.complaints(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS complaint_replies_complaint_created_idx ON public.complaint_replies(complaint_id, created_at, reply_id);

COMMIT;
